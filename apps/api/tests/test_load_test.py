class _ConcurrencyTracker:
    def __init__(self) -> None:
        self.active = 0
        self.max_seen = 0
        self.requests: list[tuple[str, str]] = []


def _tracking_asgi_app(tracker: _ConcurrencyTracker, hold_seconds: float):
    """A minimal, real ASGI application (no framework): records the
    path/method of every request and the real peak concurrent in-flight
    count, holding each request open for `hold_seconds` so overlapping
    requests actually have a chance to overlap. Exercised via
    `httpx.ASGITransport`, which drives this through the real ASGI
    scope/receive/send protocol in-process -- a genuine HTTP round trip,
    not a mocked network call.
    """

    async def app(scope, receive, send):
        assert scope["type"] == "http"
        tracker.active += 1
        tracker.max_seen = max(tracker.max_seen, tracker.active)
        tracker.requests.append((scope["method"], scope["path"]))
        await asyncio.sleep(hold_seconds)
        tracker.active -= 1
        await send({"type": "http.response.start", "status": 200, "headers": [(b"content-type", b"application/json")]})
        await send({"type": "http.response.body", "body": b"{}"})

    return app


def test_bounded_concurrency_client_never_exceeds_max_concurrency():
    tracker = _ConcurrencyTracker()
    transport = httpx.ASGITransport(app=_tracking_asgi_app(tracker, hold_seconds=0.05))
    client = BoundedConcurrencyLoadClient(base_url="http://test", max_concurrency=2, transport=transport)

    arrivals = [Arrival(t=0.0, is_burst=False) for _ in range(8)]
    items = [WorkloadItem(kind="chat", employee_id=1, payload={"message": "hi"}) for _ in range(8)]

    results = asyncio.run(client.run_schedule(arrivals, items))

    assert len(results) == 8
    assert all(r.status_code == 200 for r in results)
    assert all(r.error is None for r in results)
    # The real, observed peak concurrency must never exceed the configured bound.
    assert tracker.max_seen <= 2
    # With 8 requests at max_concurrency=2 and a non-trivial hold time,
    # real contention should actually have occurred at least once --
    # otherwise this test would pass even with a broken (unbounded)
    # semaphore just by accident of timing.
    assert tracker.max_seen == 2


def test_bounded_concurrency_client_fires_requests_at_the_right_paths_and_employee_header():
    tracker = _ConcurrencyTracker()
    transport = httpx.ASGITransport(app=_tracking_asgi_app(tracker, hold_seconds=0.0))
    client = BoundedConcurrencyLoadClient(base_url="http://test", max_concurrency=5, transport=transport)

    arrivals = [Arrival(t=0.0, is_burst=False), Arrival(t=0.0, is_burst=False)]
    items = [
        WorkloadItem(kind="chat", employee_id=7, payload={"message": "hi"}),
        WorkloadItem(kind="diagnose", employee_id=9, path_params={"ticket_id": 3}),
    ]

    results = asyncio.run(client.run_schedule(arrivals, items))

    assert len(results) == 2
    assert ("POST", "/chat") in tracker.requests
    assert ("POST", "/tickets/3/diagnose") in tracker.requests


