def test_build_workload_mix_draws_from_real_seeded_employees_and_golden_text(db_session):
    """Runs against whatever is REALLY seeded in the dev DB right now
    (real `Employee`/`Queue`/`Ticket` rows -- `db_session` is read-only
    here, nothing is written or rolled back that matters) plus the real
    golden-set text files. No synthetic placeholder employee ids or
    invented question strings anywhere in the output.
    """
    import random

    from resolvegrid_api.load_test import fetch_real_employee_ids, fetch_real_queue_ids

    real_employee_ids = set(fetch_real_employee_ids(db_session))
    real_queue_ids = set(fetch_real_queue_ids(db_session))
    real_questions = set(load_real_chat_questions())
    real_descriptions = set(load_real_ticket_descriptions())

    rng = random.Random(2026)
    items = build_workload_mix(db_session, rng, 60)
    assert len(items) == 60

    kinds_seen = {item.kind for item in items}
    assert kinds_seen <= {"chat", "create_ticket", "diagnose"}

    for item in items:
        assert item.employee_id in real_employee_ids
        if item.kind == "chat":
            assert item.payload["message"] in real_questions
        elif item.kind == "create_ticket":
            assert item.payload["body"] in real_descriptions
            assert item.payload["queue_id"] in real_queue_ids
            assert item.payload["type"] in ("incident", "service_request")
        elif item.kind == "diagnose":
            assert isinstance(item.path_params["ticket_id"], int)


