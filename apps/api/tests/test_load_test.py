def test_bounded_concurrency_client_records_connection_errors_without_raising():
    """A request against a base_url with no real transport configured
    (so httpx actually attempts and fails a real outbound connection,
    rather than anything being mocked) must be recorded as a
    `RequestResult` with `error` set, never raised out of `run_schedule`.
    """
    client = BoundedConcurrencyLoadClient(
        base_url="http://127.0.0.1:1", max_concurrency=1, timeout_seconds=2.0
    )
    arrivals = [Arrival(t=0.0, is_burst=False)]
    items = [WorkloadItem(kind="chat", employee_id=1, payload={"message": "hi"})]

    results = asyncio.run(client.run_schedule(arrivals, items))

    assert len(results) == 1
    assert results[0].status_code is None
    assert results[0].error is not None
