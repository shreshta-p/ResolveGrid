def test_build_workload_mix_only_fetches_data_sources_the_requested_mix_needs(db_session, monkeypatch):
    """Code-review fix: `build_workload_mix` used to unconditionally fetch
    real `Queue`/`Ticket` ids and both golden-set text files regardless of
    which `kind`s a caller's `mix` actually requested -- so a caller
    passing `mix={"chat": 1.0}` would still trip `fetch_real_queue_ids`'s
    "no Queue rows found" error for a workload that was never going to
    create a ticket at all. Patches the other three fetchers to raise if
    called at all, proving a chat-only mix genuinely skips them rather
    than merely happening to succeed because this dev DB has queues/
    tickets seeded.
    """
    import random

    import resolvegrid_api.load_test as load_test_module

    def _must_not_be_called(*_args, **_kwargs):
        raise AssertionError("must not be called for a mix that excludes create_ticket/diagnose")

    monkeypatch.setattr(load_test_module, "fetch_real_queue_ids", _must_not_be_called)
    monkeypatch.setattr(load_test_module, "fetch_real_ticket_ids", _must_not_be_called)
    monkeypatch.setattr(load_test_module, "load_real_ticket_descriptions", _must_not_be_called)

    items = build_workload_mix(db_session, random.Random(1), 10, mix={"chat": 1.0})
    assert len(items) == 10
    assert all(item.kind == "chat" for item in items)


